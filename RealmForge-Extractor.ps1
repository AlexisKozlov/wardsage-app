// ===== src/MiniJson.cs =====
// RealmForge extractor - a tiny JSON reader/writer.
//
// .NET Framework has no JSON parser in the assemblies that Add-Type references by default, and the
// extractor must not depend on anything that is not already on a Windows machine. This one is small
// and strict: it is used for server replies, config.json and for checking our own account.json.


namespace RealmForge {
  public static class MiniJson {
    // Returns Dictionary<string, object>, List<object>, string, double, bool or null.
    // Throws FormatException on malformed input.
    public static object Parse(string text) {
      if (text == null) throw new FormatException("empty");
      var p = new Parser(text);
      p.Ws();
      if (p.Pos < text.Length && text[p.Pos] == '﻿') { p.Pos++; p.Ws(); }
      object v = p.Value(0);
      p.Ws();
      if (p.Pos != text.Length) throw new FormatException("trailing data at " + p.Pos);
      return v;
    }

    // Like Parse, but returns null instead of throwing.
    public static object TryParse(string text) {
      try { return Parse(text); } catch (FormatException) { return null; }
    }

    public static string Quote(string s) {
      var sb = new StringBuilder(s.Length + 2);
      sb.Append('"');
      foreach (char c in s) {
        switch (c) {
          case '"': sb.Append("\\\""); break;
          case '\\': sb.Append("\\\\"); break;
          case '\n': sb.Append("\\n"); break;
          case '\r': sb.Append("\\r"); break;
          case '\t': sb.Append("\\t"); break;
          default:
            if (c < 32) sb.Append("\\u" + ((int)c).ToString("x4")); else sb.Append(c);
            break;
        }
      }
      sb.Append('"');
      return sb.ToString();
    }

    // --- helpers for reading parsed values ---
    public static Dictionary<string, object> AsObject(object o) { return o as Dictionary<string, object>; }

    public static string GetString(Dictionary<string, object> d, string key) {
      object v; if (d == null || !d.TryGetValue(key, out v)) return null;
      return v as string;
    }

    public static bool GetBool(Dictionary<string, object> d, string key, bool fallback) {
      object v; if (d == null || !d.TryGetValue(key, out v) || !(v is bool)) return fallback;
      return (bool)v;
    }

    // Returns -1 when the key is missing or not a non-negative whole number.
    public static int GetCount(Dictionary<string, object> d, string key) {
      object v; if (d == null || !d.TryGetValue(key, out v) || !(v is double)) return -1;
      double x = (double)v;
      if (x < 0 || x > int.MaxValue || Math.Floor(x) != x) return -1;
      return (int)x;
    }

    // Number of entries of an array or object value; -1 when missing.
    public static int CountOf(Dictionary<string, object> d, string key) {
      object v; if (d == null || !d.TryGetValue(key, out v) || v == null) return -1;
      var list = v as List<object>; if (list != null) return list.Count;
      var obj = v as Dictionary<string, object>; if (obj != null) return obj.Count;
      return -1;
    }

    sealed class Parser {
      const int MaxDepth = 256;
      readonly string s;
      public int Pos;
      public Parser(string text) { s = text; }

      public void Ws() {
        while (Pos < s.Length) {
          char c = s[Pos];
          if (c == ' ' || c == '\t' || c == '\n' || c == '\r') Pos++; else break;
        }
      }

      FormatException Err(string what) { return new FormatException(what + " at " + Pos); }

      public object Value(int depth) {
        if (depth > MaxDepth) throw Err("nesting too deep");
        if (Pos >= s.Length) throw Err("unexpected end");
        char c = s[Pos];
        if (c == '{') return Obj(depth);
        if (c == '[') return Arr(depth);
        if (c == '"') return Str();
        if (c == 't') { Lit("true"); return true; }
        if (c == 'f') { Lit("false"); return false; }
        if (c == 'n') { Lit("null"); return null; }
        if (c == '-' || (c >= '0' && c <= '9')) return Num();
        throw Err("unexpected '" + c + "'");
      }

      void Lit(string word) {
        if (string.CompareOrdinal(s, Pos, word, 0, word.Length) != 0) throw Err("bad literal");
        Pos += word.Length;
      }

      Dictionary<string, object> Obj(int depth) {
        var d = new Dictionary<string, object>();
        Pos++; Ws();
        if (Pos < s.Length && s[Pos] == '}') { Pos++; return d; }
        while (true) {
          Ws();
          if (Pos >= s.Length || s[Pos] != '"') throw Err("expected key");
          string k = Str(); Ws();
          if (Pos >= s.Length || s[Pos] != ':') throw Err("expected ':'");
          Pos++; Ws();
          d[k] = Value(depth + 1); Ws();
          if (Pos >= s.Length) throw Err("unexpected end");
          if (s[Pos] == ',') { Pos++; continue; }
          if (s[Pos] == '}') { Pos++; return d; }
          throw Err("expected ',' or '}'");
        }
      }

      List<object> Arr(int depth) {
        var a = new List<object>();
        Pos++; Ws();
        if (Pos < s.Length && s[Pos] == ']') { Pos++; return a; }
        while (true) {
          Ws();
          a.Add(Value(depth + 1)); Ws();
          if (Pos >= s.Length) throw Err("unexpected end");
          if (s[Pos] == ',') { Pos++; continue; }
          if (s[Pos] == ']') { Pos++; return a; }
          throw Err("expected ',' or ']'");
        }
      }

      string Str() {
        Pos++; // opening quote
        var sb = new StringBuilder();
        while (true) {
          if (Pos >= s.Length) throw Err("unterminated string");
          char c = s[Pos++];
          if (c == '"') return sb.ToString();
          if (c != '\\') { sb.Append(c); continue; }
          if (Pos >= s.Length) throw Err("bad escape");
          char e = s[Pos++];
          switch (e) {
            case '"': sb.Append('"'); break;
            case '\\': sb.Append('\\'); break;
            case '/': sb.Append('/'); break;
            case 'b': sb.Append('\b'); break;
            case 'f': sb.Append('\f'); break;
            case 'n': sb.Append('\n'); break;
            case 'r': sb.Append('\r'); break;
            case 't': sb.Append('\t'); break;
            case 'u':
              int code;
              if (Pos + 4 > s.Length || !int.TryParse(s.Substring(Pos, 4), NumberStyles.AllowHexSpecifier, CultureInfo.InvariantCulture, out code))
                throw Err("bad \\u escape");
              sb.Append((char)code); Pos += 4; break;
            default: throw Err("bad escape");
          }
        }
      }

      double Num() {
        int start = Pos;
        if (s[Pos] == '-') Pos++;
        while (Pos < s.Length && "0123456789+-.eE".IndexOf(s[Pos]) >= 0) Pos++;
        double d;
        if (!double.TryParse(s.Substring(start, Pos - start), NumberStyles.Float, CultureInfo.InvariantCulture, out d))
          throw Err("bad number");
        return d;
      }
    }
  }
}

// ===== src/GameInfo.cs =====
// RealmForge extractor - finding the game process and its version (read-only).


namespace RealmForge {
  public static class GameInfo {
    public const string ProcessName = "Watcher of Realms";

    // <game folder>\Watcher of Realms_Data\StreamingAssets\version\windows\realversion.xml
    static readonly string[] VersionFile = { "Watcher of Realms_Data", "StreamingAssets", "version", "windows", "realversion.xml" };

    [DllImport("kernel32.dll", SetLastError = true)]
    static extern IntPtr OpenProcess(int access, bool inherit, int pid);
    [DllImport("kernel32.dll", SetLastError = true)]
    static extern bool CloseHandle(IntPtr h);
    [DllImport("kernel32.dll", SetLastError = true, CharSet = CharSet.Unicode)]
    static extern bool QueryFullProcessImageNameW(IntPtr h, int flags, StringBuilder name, ref int size);

    const int PROCESS_QUERY_LIMITED_INFORMATION = 0x1000;

    // Id of the running game process, or 0.
    public static int FindGameProcess() {
      Process[] ps = Process.GetProcessesByName(ProcessName);
      try { return ps.Length > 0 ? ps[0].Id : 0; }
      finally { foreach (var p in ps) p.Dispose(); }
    }

    // Full path of the game exe. QueryFullProcessImageName needs only "limited information"
    // access, which usually works even for a game that runs as administrator. Returns null on failure.
    public static string TryGetExePath(int pid) {
      try {
        IntPtr h = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, false, pid);
        if (h != IntPtr.Zero) {
          try {
            var sb = new StringBuilder(1024); int size = sb.Capacity;
            if (QueryFullProcessImageNameW(h, 0, sb, ref size)) return sb.ToString(0, size);
          } finally { CloseHandle(h); }
        }
      } catch (Exception) { /* not on Windows, or the API is missing: fall through */ }
      try {
        using (var p = Process.GetProcessById(pid)) return p.MainModule.FileName;
      } catch (Exception) { return null; }
    }

    // Reads the game version from realversion.xml next to the exe. Returns null when unknown.
    public static string TryReadVersion(string exePath) {
      try {
        if (string.IsNullOrEmpty(exePath)) return null;
        string path = Path.GetDirectoryName(exePath);
        foreach (var part in VersionFile) path = Path.Combine(path, part);
        if (!File.Exists(path)) return null;
        var fi = new FileInfo(path);
        if (fi.Length > 64 * 1024) return null;
        return ParseVersionXml(File.ReadAllText(path, Encoding.UTF8));
      } catch (Exception) { return null; }
    }

    // The format of realversion.xml is not documented, so this is deliberately forgiving:
    //   1. an element or attribute whose name contains "version" (e.g. <version>1.2.3</version>, Version="1.2.3");
    //   2. otherwise the first text node that looks like a version number (1.2 / 1.2.3.4...);
    //   3. otherwise a short file without any tags is taken as the version itself.
    public static string ParseVersionXml(string xml) {
      if (xml == null) return null;
      string s = xml.Trim().TrimStart('﻿');
      s = Regex.Replace(s, @"<\?.*?\?>|<!--.*?-->", "", RegexOptions.Singleline);  // <?xml version="1.0"?> is not ours
      Match m = Regex.Match(s, @"<([A-Za-z_][\w.:-]*version[\w.:-]*)\b[^>]*>\s*([^<]+?)\s*</\1\s*>", RegexOptions.IgnoreCase);
      if (m.Success && Clean(m.Groups[2].Value) != null) return Clean(m.Groups[2].Value);
      m = Regex.Match(s, @"\b[\w.:-]*version[\w.:-]*\s*=\s*(?:""([^""]*)""|'([^']*)')", RegexOptions.IgnoreCase);
      if (m.Success) {
        string v = Clean(m.Groups[1].Success ? m.Groups[1].Value : m.Groups[2].Value);
        if (v != null) return v;
      }
      m = Regex.Match(s, @">\s*(\d+(?:\.\d+){1,4}[\w.+-]*)\s*<");
      if (m.Success) return Clean(m.Groups[1].Value);
      if (s.IndexOf('<') < 0) return Clean(s);
      return null;
    }

    static string Clean(string v) {
      if (v == null) return null;
      v = v.Trim();
      if (v.Length == 0 || v.Length > 64) return null;
      foreach (char c in v) if (c < 32 || c == '<' || c == '>') return null;
      return v;
    }
  }
}

// ===== src/Extractor.cs =====
// RealmForge extractor - the extraction pipeline around the memory reader:
// find the game -> read its version -> read memory (RFX) -> check the result.


namespace RealmForge {
  public enum ExtractError { None, GameNotRunning, AccessDenied, OpenFailed, NoAccountData, Failed }

  public sealed class ExtractResult {
    public ExtractError Error;
    public string Detail;         // extra text for the error message (Win32 code, exception message)
    public string Json;           // account.json content when Error == None
    public string GameVersion;    // may be null
    public int Heroes, Items, Artifacts;
    public int Seconds;
  }

  // Turns the log lines of RFX.Run() into a 0..1 progress value. RFX makes 13 full passes over the
  // game memory; each of the lines below is written right after one of them finishes.
  public sealed class ReadProgress {
    const int TotalPasses = 13;
    static readonly string[] PassDone = {
      "Strings found", "  nodes keyed", "  tables:", "  references:", "  equipment items (owned)", "  heroes (owned)", "  tables with '"
    };
    int passes;

    public double Feed(string line) {
      if (line != null)
        foreach (var p in PassDone)
          if (line.StartsWith(p, StringComparison.Ordinal)) { passes = Math.Min(TotalPasses, passes + 1); break; }
      return (double)passes / TotalPasses;
    }
  }

  public static class Extractor {
    internal static readonly object Gate = new object();   // RFX keeps its state in static fields: one run at a time

    public static string OutputDir {
      get { return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments), "RealmForge"); }
    }

    // Step 1: is the game running? Returns the process id (0 = not running) and the game version.
    public static int FindGame(out string gameVersion) {
      gameVersion = null;
      int pid = GameInfo.FindGameProcess();
      if (pid != 0) gameVersion = GameInfo.TryReadVersion(GameInfo.TryGetExePath(pid));
      return pid;
    }

    // Step 2: read the account from game memory. onLog receives every log line of the reader
    // (it is called on the calling thread and must not throw).
    public static ExtractResult Read(string gameVersion, Action<string> onLog) {
      var res = new ExtractResult();
      res.GameVersion = gameVersion;
      string json;
      var started = DateTime.UtcNow;
      lock (Gate) {
        RFX.Log.Length = 0;
        RFX.GameVersion = gameVersion;
        RFX.OnLog = onLog;
        try { json = RFX.Run(); }
        catch (Exception e) { res.Error = ExtractError.Failed; res.Detail = e.GetType().Name + ": " + e.Message; return res; }
        finally { RFX.OnLog = null; }

        if (json == null) {
          if (RFX.LastError == "not_running") res.Error = ExtractError.GameNotRunning;
          else if (RFX.LastError == "open_failed" && RFX.LastOpenError == 5) res.Error = ExtractError.AccessDenied;
          else if (RFX.LastError == "open_failed") { res.Error = ExtractError.OpenFailed; res.Detail = RFX.LastOpenError.ToString(); }
          else res.Error = ExtractError.Failed;
          return res;
        }
      }
      res.Seconds = (int)(DateTime.UtcNow - started).TotalSeconds;
      return Check(json, res);
    }

    // Validates the produced JSON and counts what is in it.
    public static ExtractResult Check(string json, ExtractResult res) {
      Dictionary<string, object> root;
      try { root = MiniJson.Parse(json) as Dictionary<string, object>; }
      catch (FormatException e) { res.Error = ExtractError.Failed; res.Detail = "invalid JSON: " + e.Message; return res; }
      if (root == null) { res.Error = ExtractError.Failed; res.Detail = "invalid JSON root"; return res; }
      res.Heroes = Math.Max(0, MiniJson.CountOf(root, "heroes"));
      res.Items = Math.Max(0, MiniJson.CountOf(root, "equipment"));
      res.Artifacts = Math.Max(0, MiniJson.CountOf(root, "artifacts"));
      if (res.Heroes == 0 && res.Items == 0) { res.Error = ExtractError.NoAccountData; return res; }
      res.Json = json;
      return res;
    }

    // Writes account.json and extract_log.txt to Documents\RealmForge. Returns the account.json path.
    public static string SaveCopy(string json, string log) {
      string dir = OutputDir;
      Directory.CreateDirectory(dir);
      var enc = new UTF8Encoding(false);
      string path = Path.Combine(dir, "account.json");
      File.WriteAllText(path, json, enc);
      if (log != null) File.WriteAllText(Path.Combine(dir, "extract_log.txt"), log, enc);
      return path;
    }
  }
}

// ===== src/SyncClient.cs =====
// RealmForge extractor - sending account.json to the RealmForge site.
//
// Contract (fixed, implemented by the site):
//   POST {site}/api/sync
//   Authorization: Bearer <sync code>        Content-Type: application/json
//   Content-Encoding: gzip (body = gzip of UTF-8 account.json)
//   X-RF-Extractor: 0.5                      User-Agent: RealmForge-Extractor/0.5
// Replies (JSON):
//   200 {ok:true, snapshotId, heroes, items, artifacts, viewUrl}
//   401 invalid_token | 413 too_large | 415 | 422 {error:"invalid_payload", details} | 429 rate_limited | 500
// Nothing else is sent anywhere: no telemetry, no third-party services.


namespace RealmForge {
  public enum SyncStatus {
    Ok, InvalidToken, TooLarge, UnsupportedMedia, InvalidPayload, RateLimited, ServerError,
    Redirect, Timeout, Unreachable, Unexpected
  }

  public sealed class SyncResult {
    public SyncStatus Status;
    public int HttpCode;              // 0 when there was no HTTP response
    public string SnapshotId;
    public int Heroes = -1, Items = -1, Artifacts = -1;   // -1 = not in the reply
    public string ViewUrl;            // absolute http(s) URL or null
    public string Details;            // 422 details / network error text / redirect target
    public int RetryAfterSeconds = -1;
  }

  public static class SyncClient {
    public const string Version = RFX.ExtractorVersion;
    public const string UserAgent = "RealmForge-Extractor/" + Version;
    public const string DefaultSite = "https://realmforge-wor.vercel.app";
    public static int TimeoutMs = 60000;   // per request; a field (not const) so tests can shorten it
    const int MaxReplyBytes = 1024 * 1024;

    static readonly Regex CodeRx = new Regex("^rf_[0-9A-Za-z]{32}$");
    static readonly Regex CodeInTextRx = new Regex("(?<![0-9A-Za-z_])rf_[0-9A-Za-z]{32}(?![0-9A-Za-z])");

    // --- sync code ---

    public static bool IsValidCode(string code) { return code != null && CodeRx.IsMatch(code); }

    // Accepts pasted text such as "  rf_XXXX...  " or "Code: rf_XXXX..." and returns just the code.
    // Anything else is returned trimmed, so the user sees what they typed.
    public static string ExtractCode(string text) {
      if (text == null) return "";
      Match m = CodeInTextRx.Match(text);
      return m.Success ? m.Value : text.Trim();
    }

    // --- site address ---

    // Returns the normalized base address ("https://host[/path]", no trailing slash) or null.
    // error: null | "invalid" | "https" (plain http is allowed only for localhost, for testing).
    public static string NormalizeSite(string input, out string error) {
      error = null;
      string s = (input ?? "").Trim();
      if (s.Length == 0) { error = "invalid"; return null; }
      if (s.IndexOf("://", StringComparison.Ordinal) < 0) s = "https://" + s;
      Uri u;
      if (!Uri.TryCreate(s, UriKind.Absolute, out u) || u.Host.Length == 0 || u.Query.Length > 0 || u.Fragment.Length > 0 || u.UserInfo.Length > 0) {
        error = "invalid"; return null;
      }
      bool local = u.IsLoopback;
      if (u.Scheme == Uri.UriSchemeHttp && !local) { error = "https"; return null; }
      if (u.Scheme != Uri.UriSchemeHttp && u.Scheme != Uri.UriSchemeHttps) { error = "invalid"; return null; }
      return u.GetLeftPart(UriPartial.Path).TrimEnd('/');
    }

    // --- sending ---

    public static byte[] Gzip(string json) {
      byte[] raw = new UTF8Encoding(false).GetBytes(json);
      using (var ms = new MemoryStream()) {
        using (var gz = new GZipStream(ms, CompressionMode.Compress, true)) gz.Write(raw, 0, raw.Length);
        return ms.ToArray();
      }
    }

    // .NET Framework 4.x may default to TLS 1.0/1.1 only; the site requires TLS 1.2+.
    // TLS 1.3 is not forced on purpose: Windows 10 has no TLS 1.3 client and would fail the handshake.
    public static void EnableTls12() {
      const SecurityProtocolType Tls12 = (SecurityProtocolType)3072;
      try { ServicePointManager.SecurityProtocol |= Tls12; } catch (NotSupportedException) { }
    }

    // Sends account.json. site must come from NormalizeSite. Never throws.
    public static SyncResult Send(string site, string code, string json) {
      try {
        EnableTls12();
        ServicePointManager.Expect100Continue = false;
        byte[] body = Gzip(json);
        var req = (HttpWebRequest)WebRequest.Create(site + "/api/sync");
        req.Method = "POST";
        req.ContentType = "application/json";
        req.Accept = "application/json";
        req.UserAgent = UserAgent;
        req.Headers["Authorization"] = "Bearer " + code;
        req.Headers["Content-Encoding"] = "gzip";
        req.Headers["X-RF-Extractor"] = Version;
        req.Timeout = TimeoutMs;
        req.ReadWriteTimeout = TimeoutMs;
        req.AllowAutoRedirect = false;   // a redirected POST would turn into a GET and lose the body
        req.AutomaticDecompression = DecompressionMethods.GZip | DecompressionMethods.Deflate;
        req.ContentLength = body.Length;
        using (Stream s = req.GetRequestStream()) s.Write(body, 0, body.Length);
        using (var resp = (HttpWebResponse)req.GetResponse()) return FromResponse(resp, site);
      } catch (WebException e) {
        var resp = e.Response as HttpWebResponse;
        if (resp != null) using (resp) return FromResponse(resp, site);
        var r = new SyncResult();
        r.Status = e.Status == WebExceptionStatus.Timeout ? SyncStatus.Timeout : SyncStatus.Unreachable;
        r.Details = e.Message;
        return r;
      } catch (Exception e) {
        var r = new SyncResult();
        r.Status = SyncStatus.Unreachable;
        r.Details = e.Message;
        return r;
      }
    }

    static SyncResult FromResponse(HttpWebResponse resp, string site) {
      string body = null;
      try {
        using (Stream s = resp.GetResponseStream())
        using (var ms = new MemoryStream()) {
          var buf = new byte[16384]; int n;
          while ((n = s.Read(buf, 0, buf.Length)) > 0 && ms.Length < MaxReplyBytes) ms.Write(buf, 0, n);
          body = Encoding.UTF8.GetString(ms.ToArray());
        }
      } catch (Exception) { /* keep body == null: the status code alone is still meaningful */ }
      return Interpret((int)resp.StatusCode, body, resp.Headers["Retry-After"], resp.Headers["Location"], site);
    }

    // Maps an HTTP reply to a SyncResult. Pure function (tested without a network).
    public static SyncResult Interpret(int code, string body, string retryAfter, string location, string site) {
      var r = new SyncResult();
      r.HttpCode = code;
      var obj = MiniJson.AsObject(MiniJson.TryParse(body));
      if (code >= 200 && code < 300) {
        if (obj == null || !MiniJson.GetBool(obj, "ok", false)) { r.Status = SyncStatus.Unexpected; return r; }
        r.Status = SyncStatus.Ok;
        r.SnapshotId = MiniJson.GetString(obj, "snapshotId");
        r.Heroes = MiniJson.GetCount(obj, "heroes");
        r.Items = MiniJson.GetCount(obj, "items");
        r.Artifacts = MiniJson.GetCount(obj, "artifacts");
        r.ViewUrl = ResolveUrl(site, MiniJson.GetString(obj, "viewUrl"));
        return r;
      }
      if (code >= 300 && code < 400) {
        r.Status = SyncStatus.Redirect;
        r.Details = ResolveUrl(site, location);
        return r;
      }
      switch (code) {
        case 401: r.Status = SyncStatus.InvalidToken; break;
        case 413: r.Status = SyncStatus.TooLarge; break;
        case 415: r.Status = SyncStatus.UnsupportedMedia; break;
        case 400:
        case 422: r.Status = SyncStatus.InvalidPayload; r.Details = DetailsText(obj); break;
        case 429:
          r.Status = SyncStatus.RateLimited;
          int sec;
          if (retryAfter != null && int.TryParse(retryAfter.Trim(), out sec) && sec >= 0) r.RetryAfterSeconds = sec;
          else if (MiniJson.GetCount(obj, "retryAfter") >= 0) r.RetryAfterSeconds = MiniJson.GetCount(obj, "retryAfter");
          break;
        default: r.Status = code >= 500 && code < 600 ? SyncStatus.ServerError : SyncStatus.Unexpected; break;
      }
      return r;
    }

    // Makes a server-provided URL absolute and accepts only http(s): the reply must never make
    // the extractor open anything else (file:, ms-settings:, ...).
    public static string ResolveUrl(string site, string url) {
      if (string.IsNullOrEmpty(url)) return null;
      Uri baseUri, u;
      if (!Uri.TryCreate(site + "/", UriKind.Absolute, out baseUri)) return null;
      if (!Uri.TryCreate(baseUri, url, out u)) return null;
      if (u.Scheme != Uri.UriSchemeHttps && u.Scheme != Uri.UriSchemeHttp) return null;
      return u.AbsoluteUri;
    }

    static string DetailsText(Dictionary<string, object> obj) {
      object d;
      if (obj == null || !obj.TryGetValue("details", out d) || d == null) return null;
      var parts = new List<string>();
      var list = d as List<object>;
      if (list != null) { foreach (var x in list) { if (parts.Count == 3) { parts.Add("..."); break; } parts.Add(Short(x)); } }
      else parts.Add(Short(d));
      string s = string.Join("; ", parts.ToArray());
      return s.Length > 300 ? s.Substring(0, 300) + "..." : s;
    }

    static string Short(object x) {
      if (x == null) return "null";
      var s = x as string; if (s != null) return s;
      var o = x as Dictionary<string, object>;
      if (o != null) {
        string msg = MiniJson.GetString(o, "message") ?? MiniJson.GetString(o, "error");
        string path = MiniJson.GetString(o, "path");
        if (msg != null) return path != null ? path + ": " + msg : msg;
        return "{...}";
      }
      return Convert.ToString(x, System.Globalization.CultureInfo.InvariantCulture);
    }
  }
}

