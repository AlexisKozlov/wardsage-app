// ===== src/EquipGuide.cs =====
// RealmForge extractor - equip helper: what to tell the player next. Pure logic, tested without the game.

namespace RealmForge {
  public enum GuideKind {
    GameClosed,        // the game has exited
    OpenHero,          // open the plan's hero -> gear
    OpenSlot,          // press the slot of the next item
    Pick,              // the item is in the list: row / position
    HiddenEquipped,    // the item is on another hero and the list hides worn items
    HiddenEnhanced,    // the list hides enhanced items
    HiddenFilter,      // a set / stat / level / quality filter is on
    NotInList,         // not in the list for another reason (sold, stale data): sync again
    Done               // every item of the plan is on the hero
  }

  public enum ItemState { Waiting, Current, Done }

  public sealed class GuideStep {
    public GuideKind Kind;
    public PlanItem Item;                 // the item the step is about (null for GameClosed/OpenHero/Done)
    public int Row, Col;                  // Pick: 1-based
    public string OtherHero;              // HiddenEquipped: who wears it now (name from the plan, may be null)
    public Dictionary<long, ItemState> States = new Dictionary<long, ItemState>();
    public int DoneCount;
  }

  public static class EquipGuide {
    // Is the item on the plan's hero now? Unknown owner (table not found) counts as "not yet".
    public static bool IsOn(Plan p, EquipLive s, PlanItem it) {
      long owner; return s.Owner.TryGetValue(it.Uid, out owner) && owner == p.HeroUid;
    }

    public static GuideStep Next(Plan p, EquipLive s) {
      var g = new GuideStep();
      PlanItem next = null;
      foreach (var it in p.Items) {
        bool on = IsOn(p, s, it);
        if (on) g.DoneCount++;
        g.States[it.Uid] = on ? ItemState.Done : ItemState.Waiting;
        if (!on && next == null) next = it;
      }
      if (next != null) g.States[next.Uid] = ItemState.Current;
      if (!s.GameRunning) { g.Kind = GuideKind.GameClosed; return g; }
      if (next == null) { g.Kind = GuideKind.Done; return g; }
      g.Item = next;
      if (s.HeroUid != p.HeroUid) { g.Kind = GuideKind.OpenHero; return g; }
      if (!s.PanelOk || s.Part != next.Slot) { g.Kind = GuideKind.OpenSlot; return g; }

      int row;
      if (s.Row.TryGetValue(next.Uid, out row)) {
        int col; s.Col.TryGetValue(next.Uid, out col);
        g.Kind = GuideKind.Pick; g.Row = row; g.Col = col;
        return g;
      }
      long owner;
      if (!s.Owner.TryGetValue(next.Uid, out owner)) owner = next.FromHeroUid;
      if (owner > 0 && owner != p.HeroUid && s.HideEquipped) {
        g.Kind = GuideKind.HiddenEquipped;
        g.OtherHero = owner == next.FromHeroUid ? next.FromHeroName : null;
        return g;
      }
      if (s.HideEnhanced && next.Level > 0) { g.Kind = GuideKind.HiddenEnhanced; return g; }
      if (s.FilterActive) { g.Kind = GuideKind.HiddenFilter; return g; }
      g.Kind = GuideKind.NotInList;
      return g;
    }

    // Plan for the hero open in the game, else the current choice (index into plans), else the first.
    public static int PickPlan(List<Plan> plans, EquipLive s, int current) {
      if (plans == null || plans.Count == 0) return -1;
      if (s != null && s.HeroUid > 0) for (int i = 0; i < plans.Count; i++) if (plans[i].HeroUid == s.HeroUid) return i;
      return current >= 0 && current < plans.Count ? current : 0;
    }

    public static string ItemLine(PlanItem it) {
      string s = it.Name;
      if (it.Level > 0) s += " +" + it.Level;
      if (!string.IsNullOrEmpty(it.MainStat)) s += " · " + it.MainStat;
      return s;
    }
  }
}

// ===== src/CodeProtector.cs =====
// RealmForge extractor - encrypting the sync code with Windows DPAPI (current user).


namespace RealmForge {
  public static class CodeProtector {
    // Extra entropy: other programs of the same user cannot decrypt the blob by accident.
    static readonly byte[] Entropy = Encoding.UTF8.GetBytes("RealmForge.SyncCode.v1");

    public static string Protect(string plain) {
      byte[] data = ProtectedData.Protect(Encoding.UTF8.GetBytes(plain), Entropy, DataProtectionScope.CurrentUser);
      return Convert.ToBase64String(data);
    }

    public static string Unprotect(string base64) {
      byte[] data = ProtectedData.Unprotect(Convert.FromBase64String(base64), Entropy, DataProtectionScope.CurrentUser);
      return Encoding.UTF8.GetString(data);
    }
  }
}

// ===== src/Config.cs =====
// RealmForge extractor - settings in %APPDATA%\RealmForge\config.json.
//
// {"site":"https://realmforge-wor.vercel.app","lang":"ru","saveCopy":false,"code":"dpapi:<base64>"}
// The sync code is never stored in plain text: it is encrypted with Windows DPAPI for the current
// user (see CodeProtector), so the file is useless on another PC or under another Windows account.


namespace RealmForge {
  public sealed class AppConfig {
    public string Site = SyncClient.DefaultSite;
    public string Code = "";
    public string Lang = "ru";
    public bool SaveCopy;
    public bool AutoSync = true;    // send the account to the site by itself after gear changes and every few minutes
    public bool AutoClick = true;   // equip helper: open the slot, scroll the list and click the item in the game
    public bool AutoConfirm;        // ...and press «Заменить» itself (off by default: the player's explicit choice)
    // last successful sync (shown on the start screen; the busts of the strongest heroes decorate the banner)
    public string LastAt;                       // ISO 8601 UTC or null
    public int LastHeroes = -1, LastItems = -1, LastArtifacts = -1;
    public List<int> LastTop = new List<int>(); // base ids of the 3 strongest heroes

    const string ProtectedPrefix = "dpapi:";

    public static string DefaultDir {
      get { return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "RealmForge"); }
    }
    public static string DefaultPath { get { return Path.Combine(DefaultDir, "config.json"); } }

    public static AppConfig Load() { return Load(DefaultPath); }

    // A missing or broken file gives the defaults: settings must never stop the extractor from starting.
    public static AppConfig Load(string path) {
      try { if (File.Exists(path)) return FromJson(File.ReadAllText(path, Encoding.UTF8)); }
      catch (Exception) { }
      return new AppConfig();
    }

    public void Save() { Save(DefaultPath); }

    public void Save(string path) {
      Directory.CreateDirectory(Path.GetDirectoryName(path));
      string tmp = path + ".tmp";
      File.WriteAllText(tmp, ToJson(), new UTF8Encoding(false));
      if (File.Exists(path)) File.Delete(path);
      File.Move(tmp, path);
    }

    public string ToJson() {
      var sb = new StringBuilder();
      sb.Append("{\n  \"site\": ").Append(MiniJson.Quote(Site ?? ""));
      sb.Append(",\n  \"lang\": ").Append(MiniJson.Quote(Lang == "en" ? "en" : "ru"));
      sb.Append(",\n  \"saveCopy\": ").Append(SaveCopy ? "true" : "false");
      sb.Append(",\n  \"autoSync\": ").Append(AutoSync ? "true" : "false");
      sb.Append(",\n  \"autoClick\": ").Append(AutoClick ? "true" : "false");
      sb.Append(",\n  \"autoConfirm\": ").Append(AutoConfirm ? "true" : "false");
      string code = string.IsNullOrEmpty(Code) ? "" : ProtectedPrefix + CodeProtector.Protect(Code);
      sb.Append(",\n  \"code\": ").Append(MiniJson.Quote(code));
      if (!string.IsNullOrEmpty(LastAt)) {
        sb.Append(",\n  \"last\": {\"at\": ").Append(MiniJson.Quote(LastAt));
        sb.Append(", \"heroes\": ").Append(LastHeroes).Append(", \"items\": ").Append(LastItems).Append(", \"artifacts\": ").Append(LastArtifacts);
        sb.Append(", \"top\": [");
        for (int i = 0; i < LastTop.Count; i++) { if (i > 0) sb.Append(", "); sb.Append(LastTop[i]); }
        sb.Append("]}");
      }
      sb.Append("\n}\n");
      return sb.ToString();
    }

    public static AppConfig FromJson(string json) {
      var c = new AppConfig();
      var d = MiniJson.AsObject(MiniJson.TryParse(json));
      if (d == null) return c;
      string site = MiniJson.GetString(d, "site");
      if (!string.IsNullOrEmpty(site)) c.Site = site;
      c.Lang = MiniJson.GetString(d, "lang") == "en" ? "en" : "ru";
      c.SaveCopy = MiniJson.GetBool(d, "saveCopy", false);
      c.AutoSync = MiniJson.GetBool(d, "autoSync", true);
      c.AutoClick = MiniJson.GetBool(d, "autoClick", true);
      c.AutoConfirm = MiniJson.GetBool(d, "autoConfirm", false);
      object lv;
      var last = d.TryGetValue("last", out lv) ? MiniJson.AsObject(lv) : null;
      if (last != null && MiniJson.GetString(last, "at") != null) {
        c.LastAt = MiniJson.GetString(last, "at");
        c.LastHeroes = MiniJson.GetCount(last, "heroes");
        c.LastItems = MiniJson.GetCount(last, "items");
        c.LastArtifacts = MiniJson.GetCount(last, "artifacts");
        object tv; var top = last.TryGetValue("top", out tv) ? tv as List<object> : null;
        if (top != null) foreach (var x in top) if (x is double && (double)x > 0 && (double)x < 1e7 && c.LastTop.Count < 3) c.LastTop.Add((int)(double)x);
      }
      string code = MiniJson.GetString(d, "code");
      if (code != null && code.StartsWith(ProtectedPrefix, StringComparison.Ordinal)) {
        try { c.Code = CodeProtector.Unprotect(code.Substring(ProtectedPrefix.Length)) ?? ""; }
        catch (Exception) { c.Code = ""; }   // other user / other PC: just ask for the code again
      }
      return c;
    }
  }
