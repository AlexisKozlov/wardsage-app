// Builds src/DpsNames.cs for the DPS meter: hero id -> name (ru, en) and skill id -> name, from the site's data/hero-pages/*.json.
// Reads the web repo's origin/main through git (the working copy may be behind), or a plain folder when given.
//
//   node tools/dps-names.mjs [../wardsage-web] [--dir data/hero-pages-folder]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const dirAt = args.indexOf('--dir');
const dir = dirAt >= 0 ? args[dirAt + 1] : null;
const web = args.find((a, i) => !a.startsWith('--') && i !== dirAt + 1) || path.join(import.meta.dirname, '..', '..', 'wardsage-web');

const git = (...a) => execFileSync('git', ['-C', web, ...a], { encoding: 'utf8', maxBuffer: 1 << 28 });
let files;
if (dir) files = fs.readdirSync(dir).filter((f) => /^\d+\.json$/.test(f)).map((f) => [f, () => fs.readFileSync(path.join(dir, f), 'utf8')]);
else files = git('ls-tree', '--name-only', 'origin/main', 'data/hero-pages/').split('\n').filter((f) => /\/\d+\.json$/.test(f)).map((f) => [f, () => git('show', 'origin/main:' + f)]);

const heroes = new Map(), skills = new Map();
for (const [, read] of files) {
  const h = JSON.parse(read());
  if (!h.id || !h.n) continue;
  heroes.set(h.id, [h.n.ru || h.n.en || '', h.n.en || h.n.ru || '']);
  for (const s of h.skills || []) if (s.id && s.n && (s.n.ru || s.n.en) && !skills.has(s.id)) skills.set(s.id, [s.n.ru || s.n.en, s.n.en || s.n.ru]);
}
const esc = (t) => t.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n|]/g, ' ');
const rows = (m) => [...m].sort((a, b) => a[0] - b[0]).map(([id, [ru, en]]) => `    "${id}|${esc(ru)}|${esc(en)}"`).join(',\n');

const cs = `// GENERATED by tools/dps-names.mjs from the site's data/hero-pages (do not edit): hero and skill names for the DPS meter window.
// ${heroes.size} heroes, ${skills.size} skills. An id that is not in the tables shows as "#id"; an unknown skill as "Other (#id)".
using System;
using System.Collections.Generic;
using System.Globalization;

namespace RealmForge {
  public static class DpsNames {
    static readonly string[] HeroRows = {
${rows(heroes)}
    };
    static readonly string[] SkillRows = {
${rows(skills)}
    };

    static readonly Dictionary<int, string[]> Heroes = Load(HeroRows), Skills = Load(SkillRows);

    static Dictionary<int, string[]> Load(string[] rows) {
      var d = new Dictionary<int, string[]>();
      foreach (var r in rows) {
        var p = r.Split('|'); int id;
        if (p.Length == 3 && int.TryParse(p[0], NumberStyles.Integer, CultureInfo.InvariantCulture, out id)) d[id] = new[] { p[1], p[2] };
      }
      return d;
    }

    static string Pick(string[] n, bool ru) { return ru ? n[0] : n[1]; }

    /// <summary>The hero's name by the first id that is known (unit, base id, then hero id / 100000); otherwise "#unit".</summary>
    public static string Hero(int unit, int baseId, uint hero, bool ru) {
      string[] n;
      if (unit > 0 && Heroes.TryGetValue(unit, out n)) return Pick(n, ru);
      if (baseId > 0 && Heroes.TryGetValue(baseId, out n)) return Pick(n, ru);
      if (hero >= 100000 && Heroes.TryGetValue((int)(hero / 100000), out n)) return Pick(n, ru);
      return "#" + (unit > 0 ? unit : baseId > 0 ? baseId : (int)(hero / 100000));
    }

    public static bool KnownHero(int id) { return Heroes.ContainsKey(id); }
    public static bool KnownSkill(int id) { return Skills.ContainsKey(id); }

    /// <summary>The skill's name; an unknown id is "Прочее (#id)" / "Other (#id)".</summary>
    public static string Skill(int id, bool ru) {
      string[] n;
      if (Skills.TryGetValue(id, out n)) return Pick(n, ru);
      return (ru ? "Прочее (#" : "Other (#") + id + ")";
    }
  }
}
`;
fs.writeFileSync(path.join(import.meta.dirname, '..', 'src', 'DpsNames.cs'), cs);
console.log(`wrote src/DpsNames.cs: ${heroes.size} heroes, ${skills.size} skills`);
